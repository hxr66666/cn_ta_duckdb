// 用户自定义休市日（DATE 的 epoch days），运行时可变，线程安全
inline std::set<int32_t> &GetCustomHolidays() {
	static std::set<int32_t> holidays;
	return holidays;
}

inline std::mutex &GetHolidaysMutex() {
	static std::mutex m;
	return m;
}

