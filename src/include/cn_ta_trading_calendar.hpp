// 判断某日期是否交易日（周一~周五 且 非休市日）
inline bool IsTradingDay(date_t d) {
	int dow = Date::ExtractISODayOfTheWeek(d); // 1=周一..7=周日
	if (dow >= 6) {
		return false; // 周六/周日
	}
	return !IsHoliday(d);
}

// 判断某时间戳是否交易日（周一~周五 且 非休市日）
inline bool IsTradingDay(timestamp_t ts) {
	date_t d;
	dtime_t t;
	Timestamp::Convert(ts, d, t);
	return IsTradingDay(d);
}

